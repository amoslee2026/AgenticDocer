"""M10 鉴权与用户管理（L7 横切；ADR-007、§3 M10、REQ-M10-F01..F05）。

**两条鉴权路径，同一身份源（SSH 公钥）**：

* **agent 路径**（CLI/HTTP）：每请求 SSHSIG 签名 → :func:`verify_signature`
  （载荷含 RAW_PATH + query，S2；nonce 仅在验签通过后入库，S7）；
* **WebUI 路径**（浏览器）：挑战-响应登录换会话 Cookie → :func:`resolve_session`
  （S8：``JOIN users.status='active'``；S13：库内只存 ``SHA256(token)``）。

**授权**：四角色硬上限 + 文档集级 grant 收窄（:func:`authorize`，S5 形式化）。

**审计**：用户/密钥/授权变更与鉴权失败落 ``events``（``entity='auth'``，S1）；失败事件
``actor='anonymous'`` 且自述身份只进 ``claimed_*``（S10）。

用法（M06/M07）：

.. code-block:: python

    from agenticdocer.auth import AuthContext, require_auth, require_permission, write_context

    @app.get("/api/v1/docs")
    async def list_docs(ctx: AuthContext = Depends(require_permission("read"))): ...
"""

